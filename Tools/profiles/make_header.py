"""Resources/Profiles/*.json -> Source/Auto/StyleProfilesData.h (compiled into the plugin).

    python3 Tools/profiles/make_header.py
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ORDER = ["Tech House / House", "Afro / Latin House", "Hard Techno / Rave", "Drum & Bass", "UK Garage / Bass", "Lo-fi / Chill", "Afro Tech / Riddim"]   # = style index - 1 (append only: projects store the index)
FEATS = ["lufs_i", "st_drop", "plr", "lra", "tempo", "lowRatio", "subRatio", "lowMidRatio", "presenceRatio", "highRatio",
         "sideRatio", "lowSideRatio", "correlation", "true_peak", "plr_drop"]
profs = {}
for f in os.listdir(os.path.join(ROOT, "Resources/Profiles")):
    if f.endswith(".json"):
        d = json.load(open(os.path.join(ROOT, "Resources/Profiles", f)))
        profs[d["name"]] = d
out = ["#pragma once", "// GENERATED by Tools/profiles/make_header.py from Resources/Profiles/*.json - do not edit.", "",
       "struct ProfileStat { float median, p25, p75, min, max; };",
       "struct StyleProfileData",
       "{",
       "    const char* name;",
       "    int numTracks;",
       "    " + " ".join("ProfileStat %s;" % k for k in FEATS),
       "    float thirdOctMedian[29], thirdOctP25[29], thirdOctP75[29];",
       "};", "",
       "inline constexpr float profileThirdOctHz[29] = { " + ", ".join("%.1ff" % c for c in [25,31.5,40,50,63,80,100,125,160,200,250,315,400,500,630,800,1000,1250,1600,2000,2500,3150,4000,5000,6300,8000,10000,12500,16000]) + " };",
       "",
       "inline constexpr StyleProfileData styleProfileData[%d] = {" % len(ORDER)]
def stat(s): return "{ %.4ff, %.4ff, %.4ff, %.4ff, %.4ff }" % (s["median"], s["p25"], s["p75"], s["min"], s["max"])
def arr(a): return "{ " + ", ".join("%.2ff" % v for v in a) + " }"
for name in ORDER:
    d = profs[name]; f = d["features"]
    out.append("    { \"%s\", %d," % (name, d["n_tracks"]))
    out.append("      " + ", ".join(stat(f[k]) for k in FEATS) + ",")
    t = d["third_octave"]
    out.append("      %s,\n      %s,\n      %s }," % (arr(t["median_db"]), arr(t["p25"]), arr(t["p75"])))
out.append("};")
open(os.path.join(ROOT, "Source/Auto/StyleProfilesData.h"), "w").write("\n".join(out) + "\n")
print("ok", [(n, profs[n]["n_tracks"]) for n in ORDER])
